"""Aggregate GPU results.jsonl files -> tables (mean±sd over seeds, paired diff vs source_prior).

python scripts/summarize_gpu.py results/kaggle/main1 [more dirs...] --out results/gpu_summary.md
"""
import argparse
import glob
import json
import os

import numpy as np
import pandas as pd

ORDER = ["frozen", "seed_only", "naive", "verified_only", "verifier_corrected", "conf_filter", "self_filter",
         "ds_source", "vcfl", "instance_rel", "ctx_prior", "ca_vcfl", "source_prior", "ctx_eb", "ca_eb", "agree_eb",
         "ca_agree_eb", "oracle_clean"]


def load(dirs):
    rows = []
    for d in dirs:
        for f in glob.glob(os.path.join(d, "**", "results.jsonl"), recursive=True):
            env = json.load(open(os.path.join(os.path.dirname(f), "env.json")))
            for line in open(f):
                r = json.loads(line)
                r.pop("losses", None)
                r["file"] = f
                r["gpu"] = env.get("gpus", [{}])[0].get("name")
                rows.append(r)
    return pd.DataFrame(rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("dirs", nargs="+")
    ap.add_argument("--out", default=None)
    ap.add_argument("--ref", default="source_prior")
    a = ap.parse_args()
    df = load(a.dirs)
    errs = df[df.get("error").notna()] if "error" in df else df.iloc[:0]
    df = df[df.get("acc").notna()].copy()
    df.loc[df.noise_type == "bfcl_llm", "noise"] = -1.0  # real feedback: realized noise differs per seed
    key = ["noise_type", "verify_rate", "noise"]
    lines = []
    for k, g in df.groupby(key):
        lines.append(f"\n### noise_type={k[0]} verify={k[1]} noise={k[2]}  (GPU: {g.gpu.iloc[0]}, "
                     f"seeds={sorted(g.seed.unique().tolist())})\n")
        piv = g.pivot_table(index="seed", columns="method", values="acc")
        spec = dict(n=("acc", "size"), acc=("acc", "mean"), sd=("acc", "std"), seen=("acc_seen", "mean"),
                    held=("acc_held", "mean"), policy=("acc_policy", "mean"), f1=("macro_f1", "mean"),
                    gen=("gen_acc", "mean"), noisy_acc=("accepted_noisy_rate", "mean"),
                    lab_prec=("weighted_label_precision", "mean"), gpu_sec=("sec", "mean"),
                    vram=("peak_vram_gb", "max"))
        t = g.groupby("method").agg(**{k: v for k, v in spec.items() if v[0] in g.columns})
        if a.ref in piv:
            d = piv.sub(piv[a.ref], axis=0)
            t["d_vs_ref"] = d.mean()
            t["d_ci95"] = 1.96 * d.std() / np.sqrt(d.count())
        t = t.reindex([m for m in ORDER if m in t.index])
        pct = ["acc", "sd", "seen", "held", "policy", "f1", "gen", "noisy_acc", "lab_prec", "d_vs_ref", "d_ci95"]
        for c in pct:
            if c in t:
                t[c] = (100 * t[c]).round(1)
        t["gpu_sec"] = t.gpu_sec.round(0)
        t["vram"] = t.vram.round(2)
        lines.append(t.to_markdown())
    if len(errs):
        lines.append("\n### ERRORS\n" + errs[["method", "seed", "noise", "error"]].to_string())
    txt = "\n".join(lines)
    print(txt)
    if a.out:
        open(a.out, "w").write("# GPU results (auto-generated by scripts/summarize_gpu.py)\n"
                               "acc/seen/held/policy/f1/gen/d_vs_ref in %, d_vs_ref = paired diff vs "
                               f"{a.ref} (same seed), ±95% CI; gpu_sec = wall time per run incl. load+eval.\n"
                               + txt + "\n")


if __name__ == "__main__":
    main()
