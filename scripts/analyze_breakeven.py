"""Exchange-rate analysis for breakeven_cpu.py / bfcl_breakeven_cpu.py outputs (numbers come only from raw_results.csv).

For a condition, a_V(rho) = seed-mean verified-only accuracy on the rho grid (made monotone by a running max).
For method M at rho: rho_eq = a_V^{-1}(a_M(rho)) by linear interpolation; exchange rate = rho_eq / rho.
If a_M < a_V(rho) the rate is < 1 (using the unverified pool costs verifications); if a_M exceeds a_V(1) the rate is
reported as '>' (1/rho). 95% CIs: paired seed differences (normal approx.) and a seed bootstrap for the rate.
Heuristic prediction (synthetic only, uses hidden truth diagnostics): rho_pred = rho + W_u * kappa(pi) / N, with W_u the
total weight on unverified items, pi its weighted label precision and kappa(pi) = ((K pi - 1)/(K - 1))^2 the
Fisher-information factor of K-ary symmetric label noise.

python scripts/analyze_breakeven.py results/cpu_breakeven [results/cpu_bfcl_breakeven ...]
"""
from __future__ import annotations

import sys

import numpy as np
import pandas as pd

ORDER = ["naive", "verifier_corrected", "source_prior", "conf_filter", "ctx_eb", "ca_eb", "self_train",
         "oracle_clean"]


def inv_curve(rhos, accs, a):
    accs = np.maximum.accumulate(np.asarray(accs, float))
    if a <= accs[0]:
        return rhos[0]
    if a > accs[-1]:
        return np.inf
    j = int(np.searchsorted(accs, a))  # first index with accs[j] >= a
    if accs[j] == accs[j - 1]:
        return rhos[j - 1]
    t = (a - accs[j - 1]) / (accs[j] - accs[j - 1])
    return rhos[j - 1] + t * (rhos[j] - rhos[j - 1])


def analyze(df, group_cols, N=640, K=4, nboot=1000):
    out = []
    rng = np.random.default_rng(0)
    for key, g in df.groupby(group_cols):
        cur = g[g.method == "verified_only"].pivot_table(index="seed", columns="rho", values="acc")
        rhos = cur.columns.to_numpy(float)
        seeds = cur.index.to_numpy()
        for (m, rho), gm in g[(g.method != "verified_only") & (g.method != "seed_only")].groupby(["method", "rho"]):
            acc = gm.set_index("seed").acc.reindex(seeds)
            d = acc.to_numpy() - cur[rho].to_numpy()
            r_eq = inv_curve(rhos, cur.mean().to_numpy(), acc.mean())
            boots = []
            for _ in range(nboot):
                ix = rng.integers(len(seeds), size=len(seeds))
                boots.append(inv_curve(rhos, cur.iloc[ix].mean().to_numpy(), acc.iloc[ix].mean()) / rho)
            boots = np.array(boots)
            row = dict(zip(group_cols, key if isinstance(key, tuple) else (key,)))
            row.update(method=m, rho=rho, n=len(seeds), acc=acc.mean(), acc_vo=cur[rho].mean(),
                       d_vo=d.mean(), d_ci=1.96 * d.std(ddof=1) / np.sqrt(len(d)), rate=r_eq / rho,
                       rate_lo=np.quantile(boots, 0.025, method="inverted_cdf"),
                       rate_hi=np.quantile(boots, 0.975, method="inverted_cdf"),
                       saved=(r_eq - rho) * N if np.isfinite(r_eq) else np.inf)
            if "prec_unv" in gm and gm.prec_unv.notna().any():
                kap = np.clip((K * gm.prec_unv - 1) / (K - 1), 0, 1) ** 2
                row["rate_pred"] = float(((rho + gm.w_unv * kap / N) / rho).mean())
                row["prec_unv"] = float(gm.prec_unv.mean())
                row["w_unv"] = float(gm.w_unv.mean())
            out.append(row)
    return pd.DataFrame(out)


def fmt_rate(r):
    if not np.isfinite(r.rate):
        return f">{1 / r.rho:.0f}"
    return f"{r.rate:.2f} [{r.rate_lo:.2f},{r.rate_hi:.2f}]".replace("inf", "∞")


def main():
    for d in sys.argv[1:]:
        df = pd.read_csv(f"{d}/raw_results.csv")
        if "noise_type" in df:
            cols, N = ["learner", "noise_type", "noise"], 640
        else:
            cols, N = ["learner", "view"], int((df[df.method == "verified_only"].n_ver.max()))
        s = analyze(df, cols, N=N)
        s.to_csv(f"{d}/exchange_rates.csv", index=False)
        lines = [f"# Exchange rates — `{d}`", "",
                 "rate = rho_eq/rho (verified-only equivalent); >1: unverified pool worth extra verifications; "
                 "d_vo = acc − verified_only (paired, 95% CI). Generated by scripts/analyze_breakeven.py.", ""]
        for key, g in s.groupby(cols):
            vo = df[(df.method == "verified_only")]
            for c, v in zip(cols, key):
                vo = vo[vo[c] == v]
            curve = vo.groupby("rho").acc.mean()
            lines += [f"## {key}", "", "verified_only curve: " + ", ".join(f"{r:g}:{a:.3f}" for r, a in curve.items()),
                      "", "| method | rho | acc | d_vo ±CI | rate [95%] | rate_pred | prec_unv |",
                      "|---|---|---|---|---|---|---|"]
            g = g.assign(o=g.method.map({m: i for i, m in enumerate(ORDER)})).sort_values(["rho", "o"])
            for _, r in g.iterrows():
                lines.append(f"| {r.method} | {r.rho:g} | {r.acc:.3f} | {100 * r.d_vo:+.1f}±{100 * r.d_ci:.1f} | "
                             f"{fmt_rate(r)} | {r.get('rate_pred', np.nan):.2f} | {r.get('prec_unv', np.nan):.3f} |")
            lines.append("")
        open(f"{d}/exchange_rates.md", "w").write("\n".join(lines))
        print("\n".join(lines))


if __name__ == "__main__":
    main()
