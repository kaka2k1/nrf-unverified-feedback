"""PLAN_Q1 A1 analysis: verification-sampling strategies vs random (paired by seed), from results/q1_a1/raw_results.csv.

(1) Reliability-estimate bias (points): bias_global = mean q(unverified) − true unverified feedback accuracy;
    mae_cell = mean |cell-mean q − true cell accuracy|; ver_acc_gap = verified-sample accuracy − pool accuracy.
    Reported as mean ± 95% bootstrap CI over seeds (absolute values; not compared, the target for bias is 0).
(2) Downstream accuracy: strategy − random, paired; exact sign-flip p, Holm over all accuracy comparisons.

python scripts/q1_a1_stats.py  ->  results/q1_a1/summary.md, results/q1_a1/acc_vs_random.csv
"""
from __future__ import annotations

import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from scripts.q1_stats import exact_signflip_p, holm  # noqa: E402

D = "results/q1_a1"


def ci(x, rng, B=10_000):
    x = np.asarray(x, float)
    bs = x[rng.integers(len(x), size=(B, len(x)))].mean(1)
    return x.mean(), np.quantile(bs, .025), np.quantile(bs, .975)


def main():
    df = pd.read_csv(f"{D}/raw_results.csv")
    rng = np.random.default_rng(0)
    keys = ["learner", "noise_type", "noise", "rho"]
    lines = ["# A1 — which items should the verifier check? (CPU, 20 seeds)", "",
             "Generated by `scripts/q1_a1_stats.py` from `results/q1_a1/raw_results.csv` (script `q1_a1_cpu.py`).", "",
             "## 1. Reliability-estimate bias (points; mean [95% bootstrap CI]; ideal = 0)", "",
             "| learner | noise | rho | strategy | ver_acc_gap | bias_global SP | bias_global Ctx-EB | mae_cell SP | mae_cell Ctx-EB |",
             "|---|---|---|---|---|---|---|---|---|"]
    f = lambda t: f"{t[0]:+.1f} [{t[1]:+.1f},{t[2]:+.1f}]"  # noqa: E731
    for key, g in df.groupby(keys):
        for st in ["random", "suspicious", "strat_ctx", "strat_cell"]:
            gs = g[g.strategy == st]
            sp, ce = gs[gs.method == "source_prior"], gs[gs.method == "ctx_eb"]
            lines.append(f"| {key[0]} | {key[1]} {key[2]} | {key[3]} | {st} | {f(ci(sp.ver_acc_gap, rng))} | "
                         f"{f(ci(sp.bias_global, rng))} | {f(ci(ce.bias_global, rng))} | {f(ci(sp.mae_cell, rng))} | "
                         f"{f(ci(ce.mae_cell, rng))} |")
    rows, Ds = [], []
    for key, g in df.groupby(keys + ["method"]):
        piv = g.pivot_table(index="seed", columns="strategy", values="acc")
        for st in ["suspicious", "strat_ctx", "strat_cell"]:
            d = (piv[st] - piv["random"]).to_numpy()
            m, lo, hi = ci(d, rng)
            rows.append(dict(zip(keys + ["method"], key), strategy=st, acc_random=piv["random"].mean(),
                             acc=piv[st].mean(), diff=m, ci_lo=lo, ci_hi=hi,
                             d_z=d.mean() / d.std(ddof=1) if d.std(ddof=1) > 0 else np.nan))
            Ds.append(d)
    r = pd.DataFrame(rows)
    r["p"] = exact_signflip_p(np.stack(Ds, 1))
    r["p_holm"] = holm(r.p)
    r.to_csv(f"{D}/acc_vs_random.csv", index=False)
    lines += ["", f"## 2. Downstream test accuracy: strategy − random (points, paired over seeds); Holm over {len(r)} tests",
              "", "| learner | noise | rho | method | acc random | suspicious | strat_ctx | strat_cell |", "|---|---|---|---|---|---|---|---|"]
    for key, g in r.groupby(keys + ["method"]):
        g = g.set_index("strategy")
        cells = []
        for st in ["suspicious", "strat_ctx", "strat_cell"]:
            x = g.loc[st]
            s = "**" if x.p_holm < 0.01 else ("*" if x.p_holm < 0.05 else "")
            cells.append(f"{x['diff']:+.1f} [{x.ci_lo:+.1f},{x.ci_hi:+.1f}]{s}")
        lines.append(f"| {key[0]} | {key[1]} {key[2]} | {key[3]} | {key[4]} | {g.acc_random.iloc[0]:.1f} | " + " | ".join(cells) + " |")
    lines += ["", "`*`/`**`: Holm-adjusted exact sign-flip p < 0.05 / 0.01."]
    open(f"{D}/summary.md", "w").write("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
